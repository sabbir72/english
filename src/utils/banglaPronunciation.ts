/**
 * Phonetic IPA to Bengali Transliteration Engine
 * Converts arbitrary IPA notations (e.g. "/əˈbaʊt/", "/ˈbjuːtɪfl/") into Bengali phonetics
 */
export function ipaToBanglaPronunciation(ipa: string): string {
  if (!ipa) return '';

  // Strip slashes, stress marks, and brackets
  let s = ipa.replace(/[\/\\\[\]ˈˌ]/g, '').trim();

  // Multi-character diphthongs and clusters first
  const replacements: [RegExp, string][] = [
    // Vowels & Diphthongs
    [/aɪə/g, 'আয়ার'],
    [/aʊə/g, 'আওয়ার'],
    [/eɪ/g, 'এই'],
    [/aɪ/g, 'আই'],
    [/ɔɪ/g, 'অয়'],
    [/aʊ/g, 'আউ'],
    [/əʊ/g, 'ও'],
    [/oʊ/g, 'ও'],
    [/ɪə/g, 'ইয়ার'],
    [/eə/g, 'এয়ার'],
    [/ʊə/g, 'উয়ার'],
    [/ɜːr/g, 'আর'],
    [/ɜː/g, 'আর'],
    [/ɑːr/g, 'আর'],
    [/ɑː/g, 'আ'],
    [/ɔːr/g, 'অর'],
    [/ɔː/g, 'অ'],
    [/iː/g, 'ঈ'],
    [/uː/g, 'ঊ'],
    [/æ/g, 'অ্যা'],
    [/ʌ/g, 'আ'],
    [/ɒ/g, 'অ'],
    [/ɪ/g, 'ই'],
    [/i/g, 'ই'],
    [/ʊ/g, 'উ'],
    [/u/g, 'উ'],
    [/e/g, 'এ'],
    [/ə/g, 'অ্যা'],

    // Affricates and compound consonants
    [/tʃ/g, 'চ'],
    [/ʧ/g, 'চ'],
    [/dʒ/g, 'জ'],
    [/ʤ/g, 'জ'],
    [/ŋɡ/g, 'ঙ্গ'],
    [/ŋk/g, 'ঙ্ক'],
    [/ŋ/g, 'ং'],

    // Fricatives & Stops
    [/θ/g, 'থ'],
    [/ð/g, 'দ'],
    [/ʃ/g, 'শ'],
    [/ʒ/g, 'ঝ'],
    [/p/g, 'প'],
    [/b/g, 'ব'],
    [/t/g, 'ট'],
    [/d/g, 'ড'],
    [/k/g, 'ক'],
    [/ɡ/g, 'গ'],
    [/g/g, 'গ'],
    [/m/g, 'ম'],
    [/n/g, 'ন'],
    [/l/g, 'ল'],
    [/r/g, 'র'],
    [/f/g, 'ফ'],
    [/v/g, 'ভ'],
    [/s/g, 'স'],
    [/z/g, 'জ'],
    [/h/g, 'হ'],
    [/w/g, 'ওয়'],
    [/j/g, 'ই'],
  ];

  for (const [pattern, rep] of replacements) {
    s = s.replace(pattern, rep);
  }

  // Polish raw transliterations into pleasing Bengali words:
  // Convert independent vowels following consonants to vowel diacritics (কার)
  const vowelMap: Record<string, string> = {
    'আ': 'া',
    'ই': 'ি',
    'ঈ': 'ী',
    'উ': 'ু',
    'ঊ': 'ূ',
    'এ': 'ে',
    'ও': 'ো',
    'অ্যা': '্যা',
  };

  const consonants = 'কখগঘঙচছজঝঞটঠডঢণতথদধনপফবভমযরলশষসহড়ঢ়য়ৎংঃঁ';
  let result = '';
  for (let i = 0; i < s.length; i++) {
    const char = s[i];
    const prev = i > 0 ? s[i - 1] : '';

    if (consonants.includes(prev) && vowelMap[char]) {
      result += vowelMap[char];
    } else {
      result += char;
    }
  }

  // Common cleanups
  return result
    .replace(/ওয়্যা/g, 'ওয়া')
    .replace(/অ্যা্যা/g, 'অ্যা')
    .replace(/াা/g, 'া')
    .replace(/িি/g, 'ি')
    .replace(/ুু/g, 'ু')
    .replace(/টশ/g, 'চ')
    .trim();
}

/**
 * Main helper to retrieve natural Bengali pronunciation for any English word
 */
export function getBanglaPronunciation(word: string, ipa?: string): string {
  if (!word) return '';

  const cleanWord = word.toLowerCase().trim();

  // 1. Direct match in curated high-frequency dictionary
  if (COMMON_BANGLA_PRONUNCIATIONS[cleanWord]) {
    return COMMON_BANGLA_PRONUNCIATIONS[cleanWord];
  }

  // Strip punctuation or plurals/inflections if possible
  const singular = cleanWord.replace(/(s|es|ed|ing)$/, '');
  if (singular && singular !== cleanWord && COMMON_BANGLA_PRONUNCIATIONS[singular]) {
    const base = COMMON_BANGLA_PRONUNCIATIONS[singular];
    if (cleanWord.endsWith('ing')) return `${base}িং`;
    if (cleanWord.endsWith('ed')) return `${base}ড`;
    if (cleanWord.endsWith('s') || cleanWord.endsWith('es')) return `${base}স`;
  }

  // 2. Transliterate from IPA if provided
  if (ipa && ipa.trim().length > 0) {
    const fromIpa = ipaToBanglaPronunciation(ipa);
    if (fromIpa && fromIpa.length >= 1) {
      return fromIpa;
    }
  }

  // 3. Simple fallback
  return cleanWord;
}
